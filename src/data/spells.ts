// ---------------------------------------------------------------- magias de criação (uma por tamanho de poção)
// O Druid cria as poções de vida e o Sorcerer as de mana, de cada tamanho, um pouco depois do nível em que a poção
// pode ser bebida. Custam bem mais mana do que a poção devolve (as grandes, proporcionalmente um pouco menos).
/** [id da magia, poção criada, quanto recupera, nível mínimo da poção, vocação, palavras] */
const CONJURES: readonly (readonly [string, string, number, number, 'druid' | 'sorcerer', string])[] = [
  ['conjure_health_small', 'potion_health', 75, 1, 'druid', 'vita gutta'],
  ['conjure_health', 'potion_health_great', 180, 12, 'druid', 'vita fons'],
  ['conjure_health_large', 'potion_health_supreme', 380, 28, 'druid', 'vita flumen'],
  ['conjure_health_spirit', 'potion_health_spirit', 650, 50, 'druid', 'vita spiritus'],
  ['conjure_health_divine', 'potion_health_divine', 1100, 75, 'druid', 'vita divina'],
  ['conjure_mana_small', 'potion_mana', 60, 1, 'sorcerer', 'mana gutta'],
  ['conjure_mana', 'potion_mana_great', 150, 12, 'sorcerer', 'mana fons'],
  ['conjure_mana_large', 'potion_mana_supreme', 300, 28, 'sorcerer', 'mana flumen'],
  ['conjure_mana_spirit', 'potion_mana_spirit', 500, 50, 'sorcerer', 'mana spiritus'],
  ['conjure_mana_divine', 'potion_mana_divine', 900, 75, 'sorcerer', 'mana divina'],
];
const CONJURE_NAMES = ['Pequena', 'Média', 'Grande', 'Espiritual', 'Divina'] as const;
/**
 * Custo em mana por ponto recuperado, por tamanho (pequena → divina). Com a mana natural fixa por vocação (como no
 * Tibia) criar ficou 30% mais barato; as lojas pagam 35% (não 50%) pelas poções, então criar para vender rende o
 * mesmo ouro por ponto de mana de antes (~0,1). Sempre acima de 1 (criar mana com mana nunca dá lucro de mana).
 */
const CONJURE_COST = [2.4, 2.25, 2.1, 1.9, 1.7] as const;

function conjureSpell(
  [id, itemId, amount, potionLevel, voc, words]: (typeof CONJURES)[number],
  i: number,
): SpellDef {
  const size = i % 5;
  const heal = voc === 'druid';
  const what = heal ? 'Vida' : 'Mana';
  const cost = Math.round(amount * CONJURE_COST[size]!);
  return {
    id,
    name: `Criar Poção de ${what} ${CONJURE_NAMES[size]}`,
    words,
    icon: heal ? 'spell_conjure_health' : 'spell_conjure_mana',
    description: `Transforma ${cost} de mana em uma Poção de ${what} ${CONJURE_NAMES[size]} (${amount} de ${what.toLowerCase()}) na mochila.`,
    vocations: [voc],
    minLevel: Math.max(6, potionLevel + 6),
    minMagicLevel: 2 + size * 4,
    manaCost: cost,
    cooldownMs: 2000,
    range: 0,
    target: 'self',
    effect: 'conjure',
    element: heal ? 'earth' : 'energy',
    conjure: { itemId, count: 1 },
    vfx: heal
      ? { impact: 'fx_heal', sfx: 'heal', color: '#4fd08a' }
      : { impact: 'fx_mana_shield', sfx: 'buff', color: '#5aa8dd' },
    tier: size + 1,
  };
}

// Recalibragem de mana (nov/2026): a mana natural ficou fixa por vocação (como no Tibia) e não cresce mais com o nível.
// Magias de ataque e a Cura Intensa ficam mais baratas, e o custo cresce menos com o nível; os graus II/III herdam isso.
// O Sorcerer gastava ~600 poções de mana em 3 h (rotação de área ≈ 38 de mana/s contra 7,5 de regeneração).
const MANA_RETUNE: Record<string, { base: number; perLevel: number }> = {
  sorcerer: { base: 0.7, perLevel: 0.5 },
  druid: { base: 0.7, perLevel: 0.5 },
  paladin: { base: 0.8, perLevel: 1 },
  knight: { base: 0.8, perLevel: 1 },
};
for (const sp of list) {
  const attack = sp.effect === 'damage';
  const partyHeal = sp.effect === 'heal' && !!sp.partyRadius;
  if (!attack && !partyHeal) continue;
  const k = MANA_RETUNE[sp.vocations[0]!];
  if (!k || sp.vocations.length > 1) continue;
  sp.manaCost = Math.max(5, Math.round(sp.manaCost * k.base));
  if (sp.manaPerLevel) sp.manaPerLevel = Math.round(sp.manaPerLevel * k.perLevel * 100) / 100;
}

const byId = new Map(list.map((x) => [x.id, x]));
const conjures = CONJURES.map(conjureSpell);
// as duas magias de criação antigas (mesmo id) viram a versão "Média" da nova série
const originals = [
  ...list.map((x) => conjures.find((c) => c.id === x.id) ?? x),
  ...conjures.filter((c) => !byId.has(c.id)),
];
// Sem graus (II/III): cada magia existe uma vez só e o efeito cresce pelo nível e pelo Magic Level/skill da fórmula.
// Saves antigos com graus na barra viram a magia base (ver normalizeHotbar). As magias de criação guardam o tamanho da
// poção em `tier` (1 = pequena … 5 = divina), só para ordenar.
const base = originals;

export const SPELLS: Readonly<Record<string, SpellDef>> = Object.fromEntries(base.map((s) => [s.id, s]));

/** Magias novas (criação de poções) de cada vocação, na ordem em que vão liberando. */
export function extraSpellsFor(voc: string): string[] {
  return base
    .filter((s) => !byId.has(s.id))
    .filter((x) => (x.vocations as readonly string[]).includes(voc))
    .sort((a, b) => a.minLevel - b.minLevel)
    .map((x) => x.id);
}
